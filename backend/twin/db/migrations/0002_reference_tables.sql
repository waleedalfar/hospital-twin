-- Reference tables (PROMPT.md §4.1). Hospitals, units, rooms and beds are filled from shared/layout.json
-- by twin.db.reference; patients by `make seed`; staff and encounters by the simulation.

CREATE TABLE hospitals (
    id     text PRIMARY KEY,
    name   text NOT NULL,
    lat    double precision NOT NULL,
    lon    double precision NOT NULL,
    status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'diverting', 'offline'))
);

CREATE TABLE units (
    id       text PRIMARY KEY,
    name     text NOT NULL,
    clinical boolean NOT NULL,
    capacity integer NOT NULL CHECK (capacity >= 0)
);

CREATE TABLE rooms (
    id    text PRIMARY KEY,
    name  text NOT NULL,
    unit  text NOT NULL REFERENCES units (id),
    floor smallint NOT NULL,
    kind  text NOT NULL,
    x1    double precision NOT NULL,
    x2    double precision NOT NULL,
    z1    double precision NOT NULL,
    z2    double precision NOT NULL
);

CREATE TABLE beds (
    bed_id      text NOT NULL,
    hospital_id text NOT NULL REFERENCES hospitals (id),
    room_id     text NOT NULL REFERENCES rooms (id),
    unit        text NOT NULL REFERENCES units (id),
    floor       smallint NOT NULL,
    x           double precision NOT NULL,
    z           double precision NOT NULL,
    rotation    double precision NOT NULL,
    PRIMARY KEY (hospital_id, bed_id)
);

CREATE TABLE staff (
    id          text PRIMARY KEY,
    hospital_id text NOT NULL REFERENCES hospitals (id),
    role        text NOT NULL CHECK (role IN ('nurse', 'doctor', 'surgeon', 'emt')),
    unit        text NOT NULL REFERENCES units (id),
    name_code   text NOT NULL
);
CREATE INDEX staff_hospital_idx ON staff (hospital_id, unit);

CREATE TABLE patients (
    id                text PRIMARY KEY,
    synthea_id        text NOT NULL UNIQUE,
    fhir              jsonb NOT NULL,
    age               integer NOT NULL CHECK (age BETWEEN 0 AND 120),
    sex               text NOT NULL CHECK (sex IN ('male', 'female')),
    comorbidity_count integer NOT NULL CHECK (comorbidity_count >= 0),
    conditions        text[] NOT NULL DEFAULT '{}'
);

CREATE TABLE encounters (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id  text NOT NULL REFERENCES patients (id),
    hospital_id text NOT NULL REFERENCES hospitals (id),
    arrived_at  timestamptz NOT NULL,
    mode        text NOT NULL CHECK (mode IN ('walk_in', 'ambulance', 'air')),
    esi         smallint NOT NULL CHECK (esi BETWEEN 1 AND 5),
    disposition text CHECK (disposition IN ('discharge', 'admit_ward', 'admit_icu', 'surgery', 'transfer')),
    ended_at    timestamptz,
    CHECK (ended_at IS NULL OR ended_at >= arrived_at)
);
CREATE INDEX encounters_patient_idx ON encounters (patient_id, arrived_at DESC);
CREATE INDEX encounters_hospital_idx ON encounters (hospital_id, arrived_at DESC);
